"""Generate the native exact-build table from the reviewed Python/JSON registry."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from wechat_compatibility import registry, NATIVE_FIELDS, LAYOUT_FIELDS


def render():
    fields = (*NATIVE_FIELDS, 'app_entry', *LAYOUT_FIELDS)
    profiles = [p for p in registry()['profiles'] if p['capabilities']['send_text']]
    text = ['#pragma once', '// Generated by scripts/generate_compatibility.py; edit profiles.json.',
            'enum class CoreField { ' + ', '.join(fields) + ' };',
            'struct CoreBuild { LONG id; uint64_t bytes; uint32_t timestamp, image_size; unsigned char sha256[32]; };',
            'static constexpr CoreBuild core_builds[] = {']
    for profile in profiles:
        for build in profile['builds']:
            text.append('{%d,%dull,0x%x,0x%x,{%s}},' % (profile['native']['id'], build['bytes'], build['timestamp'], build['image_size'],
                        ','.join('0x'+build['sha256'][i:i+2] for i in range(0,64,2))))
    text += ['};', 'static volatile LONG core_profile_id = 0;',
             'static bool core_size_supported(uint64_t bytes) {',
             ' for (const auto& build: core_builds) if (build.bytes == bytes) return true; return false;', '}',
             'static bool core_select_build(uint64_t bytes, const unsigned char* digest, uint32_t timestamp, uint32_t image_size) {',
             ' for (const auto& build: core_builds) {',
             '  if (build.bytes == bytes && build.timestamp == timestamp && build.image_size == image_size && std::equal(build.sha256,build.sha256+32,digest)) {',
             '   InterlockedExchange(&core_profile_id,build.id); return true;', '  }', ' }',
             ' InterlockedExchange(&core_profile_id,0); return false;', '}',
             'static uintptr_t core_offset(CoreField field) {',
             ' switch (InterlockedCompareExchange(&core_profile_id,0,0)) {']
    for profile in profiles:
        values = {**profile['native']['rvas'], 'app_entry': profile['native']['app_entry'], **profile['layout']}
        text += [' case %d: switch (field) {' % profile['native']['id']]
        text += ['  case CoreField::%s: return 0x%x;' % (name, values[name]) for name in fields]
        text += [' } break;']
    text += [' }', ' RaiseException(ERROR_INVALID_DATA,0,0,nullptr); return 0;', '}',
             'static uintptr_t core_address(uintptr_t base, CoreField field) { return base + core_offset(field); }', '']
    return '\n'.join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'native_send/core_version.h'
    content = render()
    if args.check:
        if path.read_text(encoding='utf-8') != content:
            raise SystemExit('Compatibility header is stale; run scripts/generate_compatibility.py')
    else:
        path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
